export type DateRow = {
  anchor: string;
  anchorDay: number | null;
  recurrence: Recurrence;
  from: string;
  to: string;
  dates: string[];
};

const RECURRENCES: readonly Recurrence[] = ['weekly', 'monthly', 'quarterly', 'yearly', 'period'];
const ISO = /^\d{4}-\d{2}-\d{2}$/;

/** A real calendar day, not just the shape of one: 2027-02-29 fails. */
function isDay(value: string): boolean {
  if (!ISO.test(value)) return false;
  const [year, month, day] = value.split('-').map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  return date.getUTCMonth() === month - 1 && date.getUTCDate() === day;
}

export function dateRows(table: string = DATE_TABLE): DateRow[] {
  return table
    .split('\n')
    .filter((line) => line.trim() !== '' && !line.trim().startsWith('#'))
    .map((line) => {
      const [inputs, outputs = ''] = line.split('|');
      const [anchor, day, recurrence, from, to, ...extra] = inputs.trim().split(/\s+/);
      const dates = outputs.trim() === '' ? [] : outputs.trim().split(/\s+/);
      if (extra.length > 0 || !RECURRENCES.includes(recurrence as Recurrence)) {
        throw new Error(`Unreadable row: ${line}`);
      }
      return {
        anchor,
        anchorDay: day === '-' ? null : Number(day),
        recurrence: recurrence as Recurrence,
        from,
        to,
        dates,
      };
    });
}

const label = (row: DateRow) =>
  `${row.anchor} ${row.anchorDay ?? '-'} ${row.recurrence} ${row.from}..${row.to}`;

describe('the shared date table', () => {
  const rows = dateRows();

  it('is read as written: every row, every day a real one, oldest first, inside its window', () => {
    expect(rows).toHaveLength(45);
    for (const row of rows) {
      expect([label(row), [row.anchor, row.from, row.to, ...row.dates].every(isDay)]).toEqual([
        label(row),
        true,
      ]);
      expect([label(row), row.anchorDay === null || Number.isInteger(row.anchorDay)]).toEqual([
        label(row),
        true,
      ]);
      expect([label(row), row.dates]).toEqual([
        label(row),
        [...new Set(row.dates)].filter((date) => date >= row.from && date <= row.to).sort(),
      ]);
    }
  });

  it.each(rows.map((row) => [label(row), row] as const))('%s', (_, row) => {
    expect(
      occurrencesInRange(row.anchor, row.recurrence, row.from, row.to, row.anchorDay).sort(),
    ).toEqual(row.dates);
  });
});
