/**
 * Add Loan schedules worked out by an independent reference that shares no code with
 * `@/lib/loan`: a Python script on exact fractions with its own calendar, written from the rules:
 *
 * - first payment: the payment day of the month after the start when that day is on or after the
 *   start's day, else of the month after that, clamped to the month's end;
 * - later payments: the first payment's month + k, on min(payment day, days in that month);
 * - interest: actual/365 from the start date, balance¢ × rate × days / 365, rounded half up once a
 *   period; the last payment settles the balance;
 * - the solved payment: P · ∏(1 + r·dₖ) / Σₖ ∏ⱼ₌ₖ₊₁(1 + r·dⱼ), exact, rounded half up.
 *
 * Rows are [date, days, interest¢, paid¢, balance¢ after].
 */

export type ReferenceRowTuple = readonly [string, number, number, number, number];

export type AddLoanReference = {
  principal: number;
  annualRate: number;
  months: number;
  /** yyyy-mm-dd, the start date (funded_on). */
  start: string;
  paymentDay: number;
  /** yyyy-mm-dd */
  firstPayment: string;
  /** The payment the closed form gives, in cents. */
  solvedCents: number;
  /** The payment the schedule runs at, in cents. */
  paymentCents: number;
  rows: readonly ReferenceRowTuple[];
};

