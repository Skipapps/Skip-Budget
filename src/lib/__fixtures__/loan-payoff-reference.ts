/**
 * Payoff schedules worked out by an independent reference that shares no code with `@/lib/loan`:
 * a Python script on exact fractions with its own calendar, written from the P3 rules (the
 * Founder's F2: interest first, then the balance, for full and partial payoffs):
 *
 * - due dates: the first payment, then the payment day of each later month, clamped to its end;
 *   funding as given, else a month before the first payment;
 * - an unsplit period posts balance¢ × rate × days/365 (actual/365), days/360 (actual/360),
 *   days₃₀/360 (30/360) or rate/12 (monthly rests; the opening period months/12 + days/365),
 *   rounded half up once;
 * - a payoff dated inside a period posts the interest built up since the last payment or payoff
 *   (per diem; actual/365 on monthly rests), rounded half up once, and pays it first; interest it
 *   does not cover is paid first by the next payment; the rest comes off principal; one that
 *   clears the balance ends the loan, with no row after it;
 * - a payoff on a due date posts after that day's payment; payoffs the same day post in order;
 * - the rest of a split period accrues on the new balance from the payoff day;
 * - the level payment never changes, a changed payment replaces it for its number, and the last
 *   payment settles what is left;
 * - a quote is what a payoff of "everything" posts on that day, after all dated that day.
 *
 * Rows are [date, days, interest¢, paid¢, balance¢ after]. Payoffs are
 * [date, amount¢, interest¢, principal¢, balance¢ after, cleared the loan, payments before it].
 */

import type { AccrualBasis } from '@/lib/loan';

export type PayoffRowTuple = readonly [string, number, number, number, number];
export type PayoffPostingTuple = readonly [string, number, number, number, number, boolean, number];

export type PayoffReference = {
  principalCents: number;
  /** Percent, as text so it is exact. */
  rate: string;
  months: number;
  /** yyyy-mm-dd */
  firstPayment: string;
  /** yyyy-mm-dd; absent for a month before the first payment. */
  fundedOn?: string;
  paymentDay?: number;
  basis: AccrualBasis;
  paymentCents: number;
  /** Changed payments, by number, in cents. */
  changes?: Readonly<Record<number, number>>;
  /** [yyyy-mm-dd, cents], in the order they were paid. */
  payoffs: readonly (readonly [string, number])[];
  rows: readonly PayoffRowTuple[];
  posts: readonly PayoffPostingTuple[];
  /** Σ interest¢ and Σ paid¢, payoffs included. */
  interestCents: number;
  paidCents: number;
  /** yyyy-mm-dd → what clears the loan that day, in cents… */
  quotes?: Readonly<Record<string, number>>;
  /** …with the first this many of `payoffs` paid (the rest is a quote paid in full). */
  quotePayoffs?: number;
};

export type PayoffSample = Omit<PayoffReference, 'rows'> & {
  rowCount: number;
  lastRow: PayoffRowTuple | null;
};
